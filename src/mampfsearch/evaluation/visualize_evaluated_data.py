import matplotlib.pyplot as plt
import pandas as pd
import numpy as np
import seaborn as sns
from math import pi
import os

# --- Configuration ---
# Defaults (can be overridden by arguments)
DEFAULT_QUESTION_GENERATION_MODEL = "Gpt 5.2"
DEFAULT_EVALUATION_MODEL = "Gpt 5.2"

# Title/spacing tuning
TITLE_PAD = 18  # vertical space between title and axes (in points)
RADAR_TITLE_Y = 1.10
RADAR_SUBPLOT_TOP = 0.82  # shrink axes a bit to create more title headroom

# Radar plot focus: highlight and (optionally) zoom into the 3–5 range
RADAR_HIGHLIGHT_BAND = (3.0, 5.0)  # (low, high)
RADAR_ZOOM_MIN = 2.0
# Zoom modes: "always" (zoom as much as possible), "auto" (zoom only if all means >= RADAR_ZOOM_MIN), "none".
RADAR_ZOOM_MODE = "always"

# Boxplot readability: show mean + finer y ticks
BOXPLOT_SHOW_MEANS = True
BOXPLOT_OVERLAY_MEAN_POINTS = True
BOXPLOT_YTICK_STEP = 0.25
BOXPLOT_YTICK_DECIMALS = 1

# The specific score columns based on your header
SCORE_COLUMNS = [
    # "clarity_score",
    "conciseness_score",
    # "relevance_score",
    # "consistency_score",
    # "answerability_score",
    "answer_consistency_score",
    "educational_complexity_score",
    "independence_score",
    "overall_review_score",
]

LABELS_MAP = {
    "clarity_score": "Clarity",
    "conciseness_score": "Conciseness",
    "relevance_score": "Relevance",
    "consistency_score": "Consistency",
    "answerability_score": "Answerability",
    "answer_consistency_score": "Ans. Consistency",
    "educational_complexity_score": "Complexity",
    "independence_score": "Independence",
    "overall_review_score": "Overall",
}


def _model_info_text(qg_model, eval_model) -> str:
    return f"Questions generated by: {qg_model}    Evaluated by: {eval_model}"


def _get_sample_size_text(df) -> str:
    counts = df["Method"].value_counts().to_dict()
    return " | ".join([f"{method}: N={count}" for method, count in counts.items()])


def load_and_merge_data(baseline_path, proposed_path):
    if os.path.exists(baseline_path) and os.path.exists(proposed_path):
        print(f"Loading real data...")
        df_base = pd.read_csv(baseline_path)
        df_prop = pd.read_csv(proposed_path)

        # Add Method Labels
        df_base["Method"] = "Baseline (Unstructured)"
        df_prop["Method"] = "Proposed (Hybrid)"

        # Combine
        return pd.concat([df_base, df_prop], ignore_index=True)
    else:
        print(f"Error: Could not find files at {baseline_path} or {proposed_path}")
        return pd.DataFrame()


def save_plot(filename, output_dir):
    """Helper to save plot and close it to free memory"""
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
    path = os.path.join(output_dir, filename)
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Saved plot to: {path}")


# --- Plot 1: Radar Chart ---
def plot_radar_chart(df, output_dir, qg_model, eval_model):
    print("Generating Radar Chart...")
    df_scores = df[SCORE_COLUMNS + ["Method"]].copy()
    means = df_scores.groupby("Method").mean().reset_index()

    categories = [LABELS_MAP[c] for c in SCORE_COLUMNS]
    N = len(categories)

    angles = [n / float(N) * 2 * pi for n in range(N)]
    angles += angles[:1]

    fig, ax = plt.subplots(figsize=(9, 9), subplot_kw=dict(polar=True))
    fig.subplots_adjust(top=RADAR_SUBPLOT_TOP)

    # If everything is already above ~3, zooming the radial axis makes the
    # differences in the 3–5 range visually larger.
    all_means_min = float(means[SCORE_COLUMNS].min().min())
    if RADAR_ZOOM_MODE == "none":
        r_min = 0.0
    elif RADAR_ZOOM_MODE == "auto":
        r_min = RADAR_ZOOM_MIN if all_means_min >= RADAR_ZOOM_MIN else 0.0
    else:  # "always"
        # Zoom in, but avoid clipping if some mean dips below RADAR_ZOOM_MIN.
        r_min = RADAR_ZOOM_MIN
        if all_means_min < r_min:
            r_min = max(0.0, all_means_min - 0.1)

    # Highlight band (e.g. 3–5) as a subtle background annulus.
    band_low, band_high = RADAR_HIGHLIGHT_BAND
    theta = np.linspace(0, 2 * pi, 720)
    ax.fill_between(
        theta,
        np.full_like(theta, band_low),
        np.full_like(theta, band_high),
        color="grey",
        alpha=0.08,
        zorder=0,
    )

    # Define colors
    colors = {"Baseline (Unstructured)": "#ff7f0e", "Proposed (Hybrid)": "#1f77b4"}

    for method in df["Method"].unique():
        values = (
            means[means["Method"] == method][SCORE_COLUMNS].values.flatten().tolist()
        )
        values += values[:1]
        ax.plot(
            angles,
            values,
            linewidth=2,
            linestyle="solid",
            label=method,
            color=colors.get(method, "black"),
        )
        ax.fill(angles, values, colors.get(method, "black"), alpha=0.1)

    ax.set_theta_offset(pi / 2)
    ax.set_theta_direction(-1)
    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(categories, size=10)

    if r_min >= 3.0:
        yticks = [3, 4, 5]
    else:
        yticks = [1, 2, 3, 4, 5]

    plt.yticks(
        [t for t in yticks if t >= r_min],
        [str(t) for t in yticks if t >= r_min],
        color="grey",
        size=8,
    )
    plt.ylim(r_min, 5.5)
    ax.set_title(
        "Average Performance by Criterion"
        + "\n"
        + _model_info_text(qg_model, eval_model),
        y=RADAR_TITLE_Y,
        pad=TITLE_PAD,
        fontsize=13,
        fontweight="bold",
    )
    plt.legend(loc="upper right", bbox_to_anchor=(0.1, 0.1))

    save_plot("01_radar_comparison.svg", output_dir)


# --- Plot 2: Grouped Box Plot ---
def plot_box_chart(df, output_dir, qg_model, eval_model):
    print("Generating Box Plot...")
    target_cols = [
        "conciseness_score",
        "educational_complexity_score",
        "overall_review_score",
    ]
    df_melted = df.melt(
        id_vars="Method",
        value_vars=target_cols,
        var_name="Criterion",
        value_name="Score",
    )
    df_melted["Criterion"] = df_melted["Criterion"].map(LABELS_MAP)
    df_melted["Score"] = pd.to_numeric(df_melted["Score"], errors="coerce")

    criteria = [c for c in df_melted["Criterion"].dropna().unique().tolist()]
    fig_width = max(7, len(criteria) + 5)

    plt.figure(figsize=(fig_width, 6))
    ax = sns.boxplot(
        x="Criterion",
        y="Score",
        hue="Method",
        data=df_melted,
        palette="Set2",
        showmeans=BOXPLOT_SHOW_MEANS,
        meanprops=dict(
            marker="o",
            markerfacecolor="white",
            markeredgecolor="black",
            markersize=5,
            zorder=4,
        ),
    )

    # Overlay mean points (helps highlight small average differences like 0.4)
    if BOXPLOT_OVERLAY_MEAN_POINTS:
        # pointplot adds a second legend; keep the boxplot legend only
        handles, labels = ax.get_legend_handles_labels()
        if handles and labels:
            # First half corresponds to boxplot, second half to pointplot
            n = len(df_melted["Method"].unique())
            labels = labels[:n]

            # If only one criterion is shown (e.g., just Complexity), label boxes as
            # "Baseline - Complexity" and "Proposed - Complexity".
            if len(criteria) == 1:
                crit = criteria[0]

                def _short_method_name(method_label: str) -> str:
                    if "Baseline" in method_label:
                        return "Baseline"
                    if "Proposed" in method_label:
                        return "Proposed"
                    return method_label

                labels = [f"{_short_method_name(l)} - {crit}" for l in labels]

            ax.legend(handles[:n], labels, loc="lower right")

    ax.set_title(
        "Score Distributions" + "\n" + _model_info_text(qg_model, eval_model),
        fontsize=13,
        pad=TITLE_PAD,
    )
    plt.ylim(0.5, 5.5)
    plt.grid(axis="y", linestyle="--", alpha=0.5)
    plt.xticks(rotation=45)

    # Finer ticks + decimal labels so the eye can read non-integer means.
    from matplotlib.ticker import MultipleLocator, FormatStrFormatter

    ax.yaxis.set_major_locator(MultipleLocator(BOXPLOT_YTICK_STEP))
    ax.yaxis.set_major_formatter(FormatStrFormatter(f"%.{BOXPLOT_YTICK_DECIMALS}f"))

    save_plot("02_boxplot_distribution.svg", output_dir)


# --- Plot 3: Stacked Bar (Problem Criteria) ---
def plot_problem_criteria(df, output_dir, qg_model, eval_model):
    print("Generating Stacked Bar Chart...")
    # Focus on Complexity, Integration, and Independence
    target_cols = ["educational_complexity_score"]

    df_melted = df.melt(
        id_vars="Method",
        value_vars=target_cols,
        var_name="Criterion",
        value_name="Score",
    )
    df_melted["Criterion"] = df_melted["Criterion"].map(LABELS_MAP)

    ct = (
        pd.crosstab(
            [df_melted["Method"], df_melted["Criterion"]],
            df_melted["Score"],
            normalize="index",
        )
        * 100
    )

    # Ensure all scores 1-5 exist in columns for consistent coloring
    for i in range(1, 6):
        if i not in ct.columns:
            ct[i] = 0
    ct = ct[sorted(ct.columns)]

    fig_width = max(6, len(ct.index) * 1.8 + 3)
    ax = ct.plot(
        kind="bar",
        stacked=True,
        colormap="RdYlGn",
        figsize=(fig_width, 6),
        edgecolor="black",
        width=0.7,
    )

    ax.set_title(
        "Distribution across Complexity"
        + "\n"
        + _model_info_text(qg_model, eval_model),
        fontsize=13,
        pad=TITLE_PAD,
    )
    plt.ylabel("Percentage of Questions")
    plt.legend(title="Score", bbox_to_anchor=(1.05, 1), loc="upper left")

    # Clean x-labels
    labels = [item.get_text() for item in ax.get_xticklabels()]
    clean_labels = [
        l.replace(", ", "\n").replace("(", "").replace(")", "") for l in labels
    ]
    ax.set_xticklabels(clean_labels, rotation=0)

    save_plot("03_stacked_challenges.svg", output_dir)


def generate_evaluation_plots(
    baseline_csv,
    proposed_csv,
    output_dir,
    qg_model=DEFAULT_QUESTION_GENERATION_MODEL,
    eval_model=DEFAULT_EVALUATION_MODEL,
):
    # Ensure matplotlib doesn't try to open a window if no backend is present
    plt.switch_backend("Agg")

    df_all = load_and_merge_data(baseline_csv, proposed_csv)

    if not df_all.empty:
        print(f"Total Rows Loaded: {len(df_all)}")

        # Set style
        sns.set_style("whitegrid")

        try:
            plot_radar_chart(df_all, output_dir, qg_model, eval_model)
            plot_box_chart(df_all, output_dir, qg_model, eval_model)
            plot_problem_criteria(df_all, output_dir, qg_model, eval_model)
            print(f"\nDone! Check the '{output_dir}' folder for your images.")
        except Exception as e:
            print(f"\nAn error occurred during plotting: {e}")
            import traceback

            traceback.print_exc()
    else:
        print("No data found. Aborting.")


